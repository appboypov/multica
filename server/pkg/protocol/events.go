package protocol

// Event types for WebSocket communication between server, web clients, and daemon.
const (
	// Issue creation carries from_template. Type and placement snapshots use
	// issue:updated; committed release joins also have a membership event.
	EventIssueCreated            = "issue:created"
	EventIssueUpdated            = "issue:updated"
	EventIssueReleaseJoined      = "issue:release_joined"
	EventIssueDeleted            = "issue:deleted"
	EventIssueMetadataChanged    = "issue_metadata:changed"
	EventIssueAttachmentsChanged = "issue_attachments:changed"

	// Comment events
	EventCommentCreated       = "comment:created"
	EventCommentUpdated       = "comment:updated"
	EventCommentDeleted       = "comment:deleted"
	EventCommentResolved      = "comment:resolved"
	EventCommentUnresolved    = "comment:unresolved"
	EventReactionAdded        = "reaction:added"
	EventReactionRemoved      = "reaction:removed"
	EventIssueReactionAdded   = "issue_reaction:added"
	EventIssueReactionRemoved = "issue_reaction:removed"
	EventRunInputReacted      = "run_input:reacted"

	// Question events (ADR-0002). Both carry QuestionEventPayload; the
	// reason says what changed on question:updated.
	EventQuestionCreated = "question:created"
	EventQuestionUpdated = "question:updated"

	// Agent events
	EventAgentStatus   = "agent:status"
	EventAgentCreated  = "agent:created"
	EventAgentArchived = "agent:archived"
	EventAgentRestored = "agent:restored"
	// An agent's sessions changed. Carries AgentSessionsEventPayload,
	// no session: a reader lists the agent's sessions again.
	EventAgentSessions = "agent:sessions"

	// Task events (server <-> daemon).
	// Each event maps to a status transition on agent_task_queue. Front-end
	// subscribes by `task:` prefix and invalidates the workspace task
	// snapshot, so the granularity here is "what does the user want to see
	// change" — not "every internal status flip".
	EventTaskQueued                = "task:queued"                  // ∅ → queued (enqueue / retry create)
	EventTaskDispatch              = "task:dispatch"                // queued → dispatched (daemon claim)
	EventTaskRunning               = "task:running"                 // dispatched → running (daemon started)
	EventTaskWaitingLocalDirectory = "task:waiting_local_directory" // dispatched → waiting_local_directory (daemon parked on a busy local_directory path)
	EventTaskProgress              = "task:progress"
	EventTaskCompleted             = "task:completed" // running → completed
	EventTaskFailed                = "task:failed"    // running → failed
	EventTaskMessage               = "task:message"
	EventTaskCancelled             = "task:cancelled" // * → cancelled

	// Inbox events
	EventInboxNew           = "inbox:new"
	EventInboxRead          = "inbox:read"
	EventInboxUnread        = "inbox:unread"
	EventInboxArchived      = "inbox:archived"
	EventInboxUnarchived    = "inbox:unarchived"
	EventInboxBatchRead     = "inbox:batch-read"
	EventInboxBatchArchived = "inbox:batch-archived"

	// Member-private to-do transitions.
	EventTodoOpened = "todo:opened"
	EventTodoClosed = "todo:closed"

	// Workspace events
	EventWorkspaceUpdated = "workspace:updated"
	EventWorkspaceDeleted = "workspace:deleted"

	// Member events
	EventMemberAdded   = "member:added"
	EventMemberUpdated = "member:updated"
	EventMemberRemoved = "member:removed"

	// Subscriber events
	EventSubscriberAdded   = "subscriber:added"
	EventSubscriberRemoved = "subscriber:removed"

	// Activity events
	EventActivityCreated = "activity:created"

	// Skill events
	EventSkillCreated = "skill:created"
	EventSkillUpdated = "skill:updated"
	EventSkillDeleted = "skill:deleted"

	// Chat events
	EventChatMessage = "chat:message"
	EventChatDone    = "chat:done"
	// EventChatQuickActions supplements a finished turn with follow-up
	// suggestions generated by the daemon's post-completion pass. Sent after
	// chat:done; clients that don't know it simply never resolve the
	// (equally unknown) pending state.
	EventChatQuickActions = "chat:quick_actions"
	// EventChatCancelFinalized carries the deferred outcome of a cancelled
	// chat task once the daemon has flushed its transcript (or the sweeper
	// grace period expired): either a late "Stopped." assistant message or a
	// draft restore (#5219). Channel outbounds (Slack/Lark) deliberately do
	// not subscribe to it — cancellation stays silent on external channels.
	EventChatCancelFinalized = "chat:cancel_finalized"
	EventChatSessionCreated  = "chat:session_created"
	EventChatSessionRead     = "chat:session_read"
	EventChatSessionDeleted  = "chat:session_deleted"
	EventChatSessionUpdated  = "chat:session_updated"

	// Project events
	EventProjectCreated = "project:created"
	EventProjectUpdated = "project:updated"
	EventProjectDeleted = "project:deleted"

	// Repository events (ADR-0006). All three carry RepositoryEventPayload.
	EventRepositoryCreated = "repository:created"
	EventRepositoryUpdated = "repository:updated"
	EventRepositoryDeleted = "repository:deleted"

	// Worklane events. All three carry WorklaneEventPayload.
	EventWorklaneCreated = "worklane:created"
	EventWorklaneUpdated = "worklane:updated"
	EventWorklaneDeleted = "worklane:deleted"

	// Release line events (ADR-0010). Every write to a repository's release
	// line publishes release_line:updated with ReleaseLineEventPayload; the
	// client reads the line again.
	EventReleaseLineUpdated    = "release_line:updated"
	EventReleaseCommentCreated = "release_comment:created"

	// Organisation events. Both carry OrganisationEventPayload; there is no
	// organisation:deleted because organisations go only with their workspace.
	EventOrganisationCreated = "organisation:created"
	EventOrganisationUpdated = "organisation:updated"

	// Label events
	EventLabelCreated       = "label:created"
	EventLabelUpdated       = "label:updated"
	EventLabelDeleted       = "label:deleted"
	EventIssueLabelsChanged = "issue_labels:changed"

	// Custom property events. Definitions are archived, never deleted, so
	// there is no property:deleted — archive arrives as property:updated.
	EventPropertyCreated        = "property:created"
	EventPropertyUpdated        = "property:updated"
	EventIssuePropertiesChanged = "issue_properties:changed"

	// Issue status catalog events (MUL-6243). ONE event for all four writes
	// — create, edit, archive, reorder — rather than a verb per write, because
	// the catalog is read as a whole table and every client answers all four
	// the same way: re-read it. Splitting it would mint four contracts that no
	// consumer can tell apart, and reorder has no single row to name anyway.
	// The `action` in the payload is advisory (it makes a frame in devtools
	// self-describing); nothing routes on it.
	EventIssueStatusChanged = "issue_status:changed"

	// Pin events
	EventPinCreated   = "pin:created"
	EventPinDeleted   = "pin:deleted"
	EventPinReordered = "pin:reordered"

	// Invitation events
	EventInvitationCreated  = "invitation:created"
	EventInvitationAccepted = "invitation:accepted"
	EventInvitationDeclined = "invitation:declined"
	EventInvitationRevoked  = "invitation:revoked"

	// Autopilot events
	EventAutopilotCreated  = "autopilot:created"
	EventAutopilotUpdated  = "autopilot:updated"
	EventAutopilotDeleted  = "autopilot:deleted"
	EventAutopilotRunStart = "autopilot:run_start"
	EventAutopilotRunDone  = "autopilot:run_done"

	// Squad events
	EventSquadCreated = "squad:created"
	EventSquadUpdated = "squad:updated"
	EventSquadDeleted = "squad:deleted"

	// Daemon events
	EventDaemonHeartbeat               = "daemon:heartbeat"
	EventDaemonHeartbeatAck            = "daemon:heartbeat_ack"
	EventDaemonRegister                = "daemon:register"
	EventDaemonTaskAvailable           = "daemon:task_available"
	EventDaemonTaskSupplementAvailable = "daemon:task_supplement_available"
	EventDaemonRuntimeProfilesChanged  = "daemon:runtime_profiles_changed"
	EventDaemonWorkspacesChanged       = "daemon:workspaces_changed"
	// EventDaemonPendingWork is a runtime-scoped hint that a heartbeat-carried
	// request (model discovery, capability discovery, or local-skill import) is
	// queued for that runtime. Without it the daemon only learns about the
	// request on its next scheduled heartbeat, adding up to one HeartbeatInterval
	// (15s by default) of dead wait to an interactive UI flow (MUL-5444). The
	// hint carries no work
	// itself: the daemon still pulls the request through the normal heartbeat
	// claim, so a lost or duplicated hint is harmless.
	EventDaemonPendingWork = "daemon:pending_work"
	// Generic daemon→server request/response over the WebSocket control
	// connection (MUL-4257). The daemon sends EventDaemonRPCRequest with a
	// correlation id + method + body; the server replies EventDaemonRPCResponse
	// with the same request id. This is the transport for WS-first claim (with
	// HTTP fallback) and any future daemon→server RPC.
	EventDaemonRPCRequest  = "daemon:rpc_request"
	EventDaemonRPCResponse = "daemon:rpc_response"

	// GitHub integration events
	EventGitHubInstallationCreated = "github_installation:created"
	EventGitHubInstallationDeleted = "github_installation:deleted"
	EventPullRequestLinked         = "pull_request:linked"
	EventPullRequestUpdated        = "pull_request:updated"
	EventPullRequestUnlinked       = "pull_request:unlinked"

	// VCS integration events (Forgejo / Gitea / GitLab)
	EventVCSConnectionCreated = "vcs_connection:created"
	EventVCSConnectionDeleted = "vcs_connection:deleted"

	// Lark integration events. `created` covers both first-install
	// (UNIQUE on (workspace_id, agent_id) means at most one row per
	// agent) and re-install via UpsertLarkInstallation — front-ends
	// treat both as a single "installation appeared / refreshed"
	// notification. `revoked` flips status to 'revoked' without
	// deleting the row; the audit trail is preserved.
	EventLarkInstallationCreated = "lark_installation:created"
	EventLarkInstallationRevoked = "lark_installation:revoked"

	// Slack installation lifecycle (MUL-3666). Same semantics as the Lark
	// events: `created` covers both first install and OAuth re-install (the
	// UNIQUE on (workspace_id, agent_id, channel_type) means at most one row
	// per agent), `revoked` flips status without deleting the row. Front-ends
	// invalidate the Slack installations query on either.
	EventSlackInstallationCreated = "slack_installation:created"
	EventSlackInstallationRevoked = "slack_installation:revoked"

	// DingTalk installation lifecycle follows the same create/revoke semantics
	// as Slack's BYO channel installation. BindingUpdated shares the
	// dingtalk_installation prefix because it changes the member-scoped account
	// identifiers returned by the installation listing.
	EventDingTalkInstallationCreated   = "dingtalk_installation:created"
	EventDingTalkInstallationRevoked   = "dingtalk_installation:revoked"
	EventDingTalkAccountBindingUpdated = "dingtalk_installation:binding_updated"

	// WeCom smart-bot installation lifecycle. Same semantics as Lark /
	// Slack: `created` covers both first install and re-install via
	// UpsertChannelInstallation (the UNIQUE on (workspace_id, agent_id,
	// channel_type) means at most one row per agent); `revoked` flips
	// status without deleting the row. Front-ends invalidate the wecom
	// installations query on either.
	EventWecomInstallationCreated = "wecom_installation:created"
	EventWecomInstallationRevoked = "wecom_installation:revoked"

	// Telegram installation lifecycle. Same contract as the Slack pair:
	// front-ends invalidate the Telegram installations query on either.
	EventTelegramInstallationCreated = "telegram_installation:created"
	EventTelegramInstallationRevoked = "telegram_installation:revoked"
)

// Reasons carried by question:updated.
const (
	QuestionReasonAnswered     = "answered"
	QuestionReasonAnswerEdited = "answer_edited"
	QuestionReasonAskBack      = "ask_back"
	QuestionReasonReassigned   = "reassigned"
	QuestionReasonClosed       = "closed"
	QuestionReasonWithdrawn    = "withdrawn"
	QuestionReasonCancelled    = "cancelled"
	QuestionReasonOverdue      = "overdue"
	QuestionReasonWoken        = "woken"
	QuestionReasonLinked       = "linked"
)

// QuestionEventPayload is the payload of question:created and
// question:updated. Reason is empty on question:created. AskID and QuestionIDs
// identify the ask on creation and overdue updates; QuestionID is its first question.
// IssueIDs are the issues whose pages show the card; IssueID remains the first.
type QuestionEventPayload struct {
	QuestionID    string   `json:"question_id"`
	AskID         string   `json:"ask_id,omitempty"`
	QuestionIDs   []string `json:"question_ids,omitempty"`
	IssueID       string   `json:"issue_id"`
	IssueIDs      []string `json:"issue_ids,omitempty"`
	ChatSessionID string   `json:"chat_session_id,omitempty"`
	Reason        string   `json:"reason,omitempty"`
	EventID       string   `json:"event_id,omitempty"`
}

// RunInputReactedPayload identifies one run's marks on a delivered item.
type RunInputReactedPayload struct {
	IssueID   string  `json:"issue_id"`
	ItemKind  string  `json:"item_kind"`
	ItemID    string  `json:"item_id"`
	TaskID    string  `json:"task_id"`
	AgentID   string  `json:"agent_id"`
	SeenAt    *string `json:"seen_at"`
	HandledAt *string `json:"handled_at"`
}

// OrganisationEventPayload is the payload of organisation:created and
// organisation:updated.
type OrganisationEventPayload struct {
	OrganisationID string `json:"organisation_id"`
}

// RepositoryEventPayload is the payload of repository:created,
// repository:updated and repository:deleted.
type RepositoryEventPayload struct {
	RepositoryID string `json:"repository_id"`
	ProjectID    string `json:"project_id"`
}

// WorklaneEventPayload identifies the worklane for worklane:created,
// worklane:updated and worklane:deleted. The updated event also carries the
// worklane response with branch (nullable), state (busy or free), active_issue
// and next_issue (nullable issue refs with id, identifier and title).
type WorklaneEventPayload struct {
	WorklaneID   string `json:"worklane_id"`
	RepositoryID string `json:"repository_id"`
}

// ReleaseLineEventPayload is the payload of release_line:updated.
type ReleaseLineEventPayload struct {
	RepositoryID string `json:"repository_id"`
}

// IssueReleaseJoinedPayload names committed issue membership.
type IssueReleaseJoinedPayload struct {
	IssueID   string `json:"issue_id"`
	ReleaseID string `json:"release_id"`
}

// AgentSessionsEventPayload is the payload of agent:sessions.
type AgentSessionsEventPayload struct {
	AgentID string `json:"agent_id"`
}

// ReleaseCommentEventPayload invalidates discussion on a native release.
type ReleaseCommentEventPayload struct {
	ReleaseID string `json:"release_id"`
	CommentID string `json:"comment_id"`
}
